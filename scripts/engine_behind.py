"""Corpus pairs the pinned carve-rs declares it renders differently from the golden.

carve-rs lists them in `tests/corpus.rs` (`BEHIND_ON_PAIR`, `AHEAD_OF_PIN`), with
the HTML it renders today. This binding has no vote of its own: it may differ from
the golden on exactly those pairs, and there it must render what the engine
declares. `resources/engine-behind.txt` carries the copy, which
test/engine_behind.rb reads; `scripts/check-engine-behind.py` holds it to the engine.
"""

import pathlib
import re

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
LEDGER = REPO_ROOT / "resources" / "engine-behind.txt"

_TABLES = ("BEHIND_ON_PAIR", "AHEAD_OF_PIN")
_ENTRY = re.compile(r'\(\s*"([^"]+)",\s*"(?:[^"\\]|\\.)*",\s*r(#*)"(.*?)"\2\s*,?\s*\)', re.S)


def load(path=LEDGER):
    """slug -> declared HTML, from the binding's copy."""
    declared = {}
    if not path.is_file():
        return declared
    slug = None
    lines = []
    for line in path.read_text(encoding="utf-8").split("\n"):
        if line.startswith("== "):
            if slug is not None:
                declared[slug] = "\n".join(lines).strip()
            slug, lines = line[3:].strip(), []
        elif slug is not None:
            lines.append(line)
    if slug is not None:
        declared[slug] = "\n".join(lines).strip()
    return declared


def from_engine_source(corpus_rs):
    """slug -> declared HTML, read from carve-rs `tests/corpus.rs`."""
    declared = {}
    for table in _TABLES:
        start = re.search(rf"^const {table}: [^=]*= &\[", corpus_rs, re.M)
        if not start:
            raise ValueError(f"carve-rs tests/corpus.rs has no `{table}` table")
        end = re.search(r"^\];", corpus_rs[start.end():], re.M)
        body = corpus_rs[start.end(): start.end() + end.start()]
        for slug, _, html in _ENTRY.findall(body):
            declared[slug] = html.strip()
    return declared


def write(declared, path=LEDGER):
    parts = [
        "# Generated by scripts/check-engine-behind.py --write from the pinned carve-rs",
        "# tests/corpus.rs. Each entry is a corpus pair and the HTML the engine declares.",
        "",
    ]
    for slug in sorted(declared):
        parts += [f"== {slug}", declared[slug], ""]
    path.write_text("\n".join(parts), encoding="utf-8")
